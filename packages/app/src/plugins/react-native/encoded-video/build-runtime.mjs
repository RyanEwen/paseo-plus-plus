import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Bundles runtime/entry.ts into the private canvas document the Android host loads.
// Hermes cannot serialize functions, so the document ships as generated source text.
// Mirrors components/markdown/fence/mermaid/build-runtime.mjs.

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "../../../..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(__dirname, "runtime/entry.ts");
const output = path.join(__dirname, "runtime/html.gen.ts");

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  // WebCodecs first shipped in Chrome 94; the document only runs in Android System WebView.
  target: ["chrome94"],
  minify: true,
  logLevel: "info",
});

const rawJs = result.outputFiles[0]?.text;
if (!rawJs) {
  throw new Error("Encoded video runtime bundle produced no JavaScript");
}
// An embedded closing-script sequence would terminate the inline <script>.
const js = rawJs.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      http-equiv="Content-Security-Policy"
      content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; font-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"
    />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no"
    />
    <style>
      html,
      body,
      canvas {
        margin: 0;
        width: 100%;
        height: 100%;
        overflow: hidden;
        background: transparent;
      }
      canvas {
        display: block;
      }
    </style>
  </head>
  <body>
    <canvas></canvas>
    <script>${js}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/src/plugins/react-native/encoded-video/build-runtime.mjs.
// Do not edit by hand.

export const encodedVideoRuntimeHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
